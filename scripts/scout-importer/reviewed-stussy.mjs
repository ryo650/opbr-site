// Replay a HUMAN-REVIEWED transcription through the existing Scout Importer V1 core.
// This is not the macOS Apple Vision OCR pass; see docs/scout-importer/egghead-stussy-20261202.md.
import assert from "node:assert/strict";
import { readFile, writeFile, access } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadCharacterMaster } from "./character-master.mjs";
import { decimal } from "./decimal.mjs";
import {
  calculateScoutRates,
  calculateFinalScoutRates,
  validateScoutDraft,
  renderScoutModule,
  addScoutToIndex,
  scoutVariableName,
} from "./core.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const id = "egghead-stussy-20261202";
const name = "4-Step Egghead Scout #3";
const notice = "Normal-rate simulation only: 11 pulls cost 50 diamonds. Step-Up discounts, free steps and guaranteed 4-star slots are not simulated.";
const featuredIds = [
  "egghead-stussy",
  "unexpected-collaboration-kaku",
  "unexpected-collaboration-rob-lucci",
  "vegapunk-s-spy-stussy",
  "awakened-form-kaku",
  "cp9-blueno",
  "cp9-jabra",
  "animal-kingdom-pirates-tobi-roppo-who-s-who",
  "cp0-rob-lucci",
  "cp9-kaku",
  "cp-9-rob-lucci"
];
const characterDir = path.join(root, "src/data/characters");
const scoutPath = path.join(root, "src/data/scouts", id + ".ts");
const indexPath = path.join(root, "src/data/scouts/index.ts");

const { characters, byId } = await loadCharacterMaster(characterDir);
const pickups = featuredIds.map((characterId, i) => {
  assert.ok(byId.has(characterId), "Unknown featured character: " + characterId);
  return { characterId, rate: decimal(i === 0 ? "1" : "0.2") };
});
const rates = { totalFourStarRate: decimal("5"), threeStarRate: decimal("35"), twoStarRate: decimal("60") };
const bfUnitRate = decimal("0.0190476");
const officialBfIds = [
  "triple-x-level-boxer-ideo",
  "first-act-as-a-married-couple-charlotte-pudding",
  "blackbeard-pirates-helmsman-champ-jesus-burgess",
  "fire-fist-portgaz-d-ace",
];
for (const characterId of officialBfIds) assert.equal(byId.get(characterId)?.grade, "bf", characterId);
const rateCalculation = calculateScoutRates({
  ...rates, pickups, bfUnitRate, characters,
  bfCountOverride: officialBfIds.length,
});
const finalRates = calculateFinalScoutRates({
  ...rates, pickups, rateCalculation,
});
const draft = {
  id, name, startAt: "2026-11-18T14:00:00+09:00",
  endAt: "2026-12-02T13:59:59+09:00",
  bannerPublicPath: "/scouts/egghead-stussy-20261202.webp",
  variableName: scoutVariableName(id),
  featuredCharacter: byId.get("egghead-stussy"),
  characterIssues: [], pickups, bfUnitRate, noBf: false,
  featuredOnlyFourStarPool: false, ...rates, rateCalculation, finalRates,
};
assert.ok(draft.featuredCharacter, "Missing Egghead Stussy master record");
assert.deepEqual(validateScoutDraft(draft), []);
assert.deepEqual([Number(rateCalculation.bfCount), finalRates.bf.units, finalRates.star4.units], [4, 8n, 192n]);
const rendered = renderScoutModule(draft)
  .replace("/* This file is generated by scripts/scout-importer/import.mjs. */",
           "/* This file is generated with the Scout Importer V1 core from reviewed game rates. */")
  .replace('    rates: {', '    provisionalNotice: ' + JSON.stringify(notice) + ',' + String.fromCharCode(10) + '    rates: {');

if (process.argv.includes("--write")) {
  await writeFile(scoutPath, rendered);
  const index = await readFile(indexPath, "utf8");
  if (!index.includes('import { ' + draft.variableName + ' }')) {
    await writeFile(indexPath, addScoutToIndex(index, draft.variableName, draft.id));
  }
} else if (process.argv.includes("--check")) {
  assert.equal(await readFile(scoutPath, "utf8"), rendered, "Checked-in Scout diverges from importer renderer");
  const index = await readFile(indexPath, "utf8");
  assert.ok(index.includes('import { ' + draft.variableName + ' }'));
  assert.ok(index.includes('    ' + draft.variableName + ','));
  await access(path.join(root, "public/scouts", id + ".webp"));
} else {
  throw new Error("Use --check or --write");
}
console.log("Scout Importer V1 replay checked: 11 pickups / 5-35-60 categories / 11 pulls × 50 RD");
