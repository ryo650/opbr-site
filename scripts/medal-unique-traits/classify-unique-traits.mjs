const CATEGORY_RULES = [
  ["cooldown", /\bcooldown\b/i],
  ["damage-increase", /\bincrease\s+(?:normal attack\s+)?damage(?:\s+(?:dealt|to\b))?/i],
  ["damage-reduction", /\breduce\s+(?:tale\s+)?damage received\b/i],
  ["hp-recovery", /\brecover hp\b/i],
  ["capture-speed", /\b(?:boost|increase)\s+(?:(?:tale|tae)\s+)?capture speed\b/i],
  ["treasure-gauge", /\btreasure gauge\b/i],
  ["hp-increase", /\bincrease hp\b/i],
  ["atk-increase", /\b(?:increase atk|atk:\s*boosted)\b/i],
  ["def-increase", /\b(?:increase def|def:\s*boosted)\b/i],
  ["crit-increase", /\b(?:increase crit|crit:\s*boosted)\b/i],
  [
    "status-effect-reduction",
    /\breduce(?:s|d)?\s+(?:the\s+)?(?:duration|time)\s+of\s+(?:status effects?|clawed|capture block|aflame|tremor|stun|poison|confuse|shock|freeze|entrance|negative|bind|stolen heart|shadowless|recovery blocked|toy|edit|candyman|gold|sing-sing|intimidate|frostbite|sleep|spiderweb|ice ball|sew-sew|slow-slow|marked)\b/i,
  ],
  ["status-effect-nullification", /\bnullif(?:y|ied|ication)\b/i],
  [
    "status-effect-infliction",
    /\b(?:inflict an enemy with|(?:enemy|you) (?:is|has been) inflicted with|enemy has inflicted you with|enemy inflicted with)\b/i,
  ],
  ["power-up-down", /\b(?:atk|def|crit|spd):\s*(?:boosted|reduced)\b/i],
  ["spd-increase", /\b(?:increase spd|spd:\s*boosted)\b/i],
  ["skill-1", /\bskill\s*1\b/i],
  ["skill-2", /\bskill\s*2\b/i],
];

const MISSING_EFFECT_PATTERN = /(?:\bboost the|:)\s+(?:(?:tae|tale)\s+)?by\s+\d+(?:\.\d+)?%?\.?$/i;

export function classifyUniqueTrait(uniqueTrait) {
  return CATEGORY_RULES
    .filter(([, pattern]) => pattern.test(uniqueTrait))
    .map(([categoryId]) => categoryId);
}

export function getUniqueTraitReviewReason(uniqueTrait) {
  if (MISSING_EFFECT_PATTERN.test(uniqueTrait)) {
    return "The effect name is missing after the activation condition.";
  }
  return null;
}

export function buildUniqueTraitCategoryData(medals) {
  const categoryIdsByMedalId = {};
  const needsReview = [];

  for (const medal of medals) {
    categoryIdsByMedalId[medal.id] = classifyUniqueTrait(medal.uniqueTrait);
    const reason = getUniqueTraitReviewReason(medal.uniqueTrait);
    if (reason) {
      needsReview.push({ id: medal.id, uniqueTrait: medal.uniqueTrait, reason });
    }
  }

  return { categoryIdsByMedalId, needsReview };
}

export function summarizeUniqueTraitCategories(medals) {
  const { categoryIdsByMedalId, needsReview } = buildUniqueTraitCategoryData(medals);
  const categoryCounts = Object.fromEntries(
    CATEGORY_RULES.map(([categoryId]) => [categoryId, 0]),
  );
  for (const categoryIds of Object.values(categoryIdsByMedalId)) {
    for (const categoryId of categoryIds) {
      categoryCounts[categoryId] = (categoryCounts[categoryId] ?? 0) + 1;
    }
  }
  return { categoryCounts, needsReview };
}

export function renderUniqueTraitCategoryData(medals) {
  const { categoryIdsByMedalId, needsReview } = buildUniqueTraitCategoryData(medals);
  return `/* This file is generated by scripts/medal-unique-traits/generate.mjs. */

import type { UniqueTraitCategoryId } from "./unique-trait-categories";

export const uniqueTraitCategoryIdsByMedalId: Readonly<Record<string, readonly UniqueTraitCategoryId[]>> = ${JSON.stringify(categoryIdsByMedalId, null, 2)};

export const uniqueTraitCategoryNeedsReview = ${JSON.stringify(needsReview, null, 2)} as const;
`;
}
